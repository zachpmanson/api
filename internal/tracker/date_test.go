package tracker

import "testing"

func TestParseDate(t *testing.T) {
	for _, tc := range []struct{ input, want string }{
		{"2024-06-01", "2024-06-01T00:00:00.000Z"},
		{"2024-02-29T12:34:56Z", "2024-02-29T12:34:56.000Z"},
		{"2024-06-01T00:00:00.123456+05:30", "2024-05-31T18:30:00.123Z"},
		{"2024-06-01T23:59:59.999-04:00", "2024-06-02T03:59:59.999Z"},
		{"2024-06-01t00:00:00z", "2024-06-01T00:00:00.000Z"},
		{"1969-12-31T23:59:59.9999Z", "1969-12-31T23:59:59.999Z"},
		{"0000-01-01", "0000-01-01T00:00:00.000Z"},
		{"9999-12-31T23:59:59.999Z", "9999-12-31T23:59:59.999Z"},
	} {
		t.Run(tc.input, func(t *testing.T) {
			got, err := ParseDate(tc.input)
			if err != nil || got.Format(dateLayout) != tc.want {
				t.Fatalf("got %v (%v), want %s", got, err, tc.want)
			}
		})
	}
	for _, input := range []string{"", "not a date", "2023-02-29", "2024-02-30", "2024-13-01", "2024-00-01", "2024-06-00", "2024-6-1", "06/01/2024", "2024-06-01T00:00:00", "2024-06-01T24:00:00Z", "2024-06-01T00:60:00Z", "2024-06-01T00:00:60Z", "2024-06-01T00:00:00+24:00", "2024-06-01T00:00:00+00:60", "2024-06-01T00:00:00,123Z", "0000-01-01T00:00:00+01:00", "9999-12-31T23:59:59-01:00", "2024-06-01\n"} {
		t.Run(input, func(t *testing.T) {
			if _, err := ParseDate(input); err == nil {
				t.Fatal("accepted invalid date")
			}
		})
	}
}
